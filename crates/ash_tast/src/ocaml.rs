//! Generates the OCaml side of the format, for the compiler plugin.
//!
//! The output is an OCaml module of constants and one writer per record, built
//! from the same [`RecordDesc`]s the Rust structs are, as [`crate::haxe`] does for
//! the Haxe exporter.

use std::fmt::Write;

use crate::format::*;

const KEYWORDS: &[&str] = &[
    "and",
    "as",
    "assert",
    "begin",
    "class",
    "constraint",
    "do",
    "done",
    "downto",
    "else",
    "end",
    "exception",
    "external",
    "false",
    "for",
    "fun",
    "function",
    "functor",
    "if",
    "in",
    "include",
    "inherit",
    "initializer",
    "lazy",
    "let",
    "match",
    "method",
    "module",
    "mutable",
    "new",
    "nonrec",
    "object",
    "of",
    "open",
    "or",
    "private",
    "rec",
    "sig",
    "struct",
    "then",
    "to",
    "true",
    "try",
    "type",
    "val",
    "virtual",
    "when",
    "while",
    "with",
];

/// An identifier that is not an OCaml keyword.
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

/// `NodeRec` as `node_rec`.
fn snake(camel_case: &str) -> String {
    let mut out = String::new();
    for (i, ch) in camel_case.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.extend(ch.to_lowercase());
    }
    out
}

fn group<T: std::fmt::Display + Copy>(out: &mut String, module: &str, entries: &[(&str, T)]) {
    writeln!(out, "module {module} = struct").unwrap();
    for (name, value) in entries {
        writeln!(out, "\tlet {} = {value}", ident(&name.to_lowercase())).unwrap();
    }
    writeln!(out, "end\n").unwrap();
}

fn names(out: &mut String, binding: &str, list: &[&str]) {
    let quoted: Vec<String> = list.iter().map(|n| format!("\"{n}\"")).collect();
    writeln!(out, "let {binding} = [| {} |]\n", quoted.join("; ")).unwrap();
}

fn width(ty: &str) -> usize {
    match ty {
        "u8" => 1,
        "u16" => 2,
        "u32" => 4,
        other => panic!("no OCaml writer for wire type {other}"),
    }
}

/// The writes for one record. A run of sub-word fields that exactly fills a 4-byte
/// word is one 32-bit store; every other field is its own.
fn write_fields(out: &mut String, fields: &[FieldDesc]) {
    let mut i = 0;
    while i < fields.len() {
        let field = &fields[i];
        if field.offset.is_multiple_of(4) && field.ty != "u32" {
            let (mut j, mut bytes) = (i, 0);
            while j < fields.len()
                && fields[j].ty != "u32"
                && fields[j].offset == field.offset + bytes
            {
                bytes += width(fields[j].ty);
                j += 1;
                if bytes == 4 {
                    break;
                }
            }
            if bytes == 4 && j - i > 1 {
                let mut terms = Vec::new();
                let mut shift = 0;
                for part in &fields[i..j] {
                    let w = width(part.ty);
                    if !part.name.starts_with('_') {
                        let mask = (1u32 << (8 * w)) - 1;
                        let value = ident(part.name);
                        terms.push(if shift == 0 {
                            format!("({value} land {mask:#x})")
                        } else {
                            format!("(({value} land {mask:#x}) lsl {shift})")
                        });
                    }
                    shift += 8 * w;
                }
                let expr = if terms.is_empty() {
                    "0".to_owned()
                } else {
                    terms.join(" lor ")
                };
                writeln!(
                    out,
                    "\tBytes.set_int32_le out (at + {}) (Int32.of_int ({expr}));",
                    field.offset
                )
                .unwrap();
                i = j;
                continue;
            }
        }
        let value = if field.name.starts_with('_') {
            "0".to_owned()
        } else {
            ident(field.name)
        };
        let call = match field.ty {
            "u8" => format!("Bytes.set_uint8 out (at + {}) {value};", field.offset),
            "u16" => format!("Bytes.set_uint16_le out (at + {}) {value};", field.offset),
            _ => format!(
                "Bytes.set_int32_le out (at + {}) (Int32.of_int {value});",
                field.offset
            ),
        };
        writeln!(out, "\t{call}").unwrap();
        i += 1;
    }
}

/// The text of `ocaml/ash_tast/ml/tast_format.ml`.
pub fn generate() -> String {
    let mut out = String::new();
    let hash = schema_hash();
    writeln!(
        out,
        "(* Generated by `cargo run -p ash_tast --bin gen_ocaml`. Do not edit. *)\n\
         (* The TAST layout: constants, and one writer per record. Words are little-endian. *)\n"
    )
    .unwrap();
    writeln!(out, "let magic = {MAGIC:#010x}").unwrap();
    writeln!(out, "let version = {VERSION}").unwrap();
    writeln!(out, "let none = -1").unwrap();
    writeln!(out, "let schema_hash_lo = {:#010x}", hash as u32).unwrap();
    writeln!(out, "let schema_hash_hi = {:#010x}", (hash >> 32) as u32).unwrap();
    writeln!(out, "let section_count = {}", SECTIONS.len()).unwrap();
    for (i, section) in SECTIONS.iter().enumerate() {
        writeln!(out, "let section_{} = {i}", snake(section.name)).unwrap();
    }
    for section in SECTIONS {
        writeln!(out, "let {}_elem = {}", snake(section.name), section.elem).unwrap();
    }
    for record in RECORDS {
        writeln!(out, "let {}_size = {}", snake(record.name), record.size).unwrap();
    }
    writeln!(out).unwrap();

    for record in RECORDS {
        let params: Vec<String> = record
            .fields
            .iter()
            .filter(|f| !f.name.starts_with('_'))
            .map(|f| format!("~{}", ident(f.name)))
            .collect();
        writeln!(
            out,
            "let write_{} out at {} =",
            snake(record.name),
            params.join(" ")
        )
        .unwrap();
        write_fields(&mut out, record.fields);
        // The last statement ends with `;`, which a final `()` closes.
        writeln!(out, "\t()\n").unwrap();
    }

    group(&mut out, "Node_kind", NODE_KINDS);
    group(&mut out, "Node_flag", NODE_FLAGS);
    group(&mut out, "Const_kind", CONST_KINDS);
    group(&mut out, "Field_access", FIELD_ACCESSES);
    group(&mut out, "Module_kind", MODULE_KINDS);
    group(&mut out, "Type_kind", TYPE_KINDS);
    group(&mut out, "Class_flag", CLASS_FLAGS);
    group(&mut out, "Field_flag", FIELD_FLAGS);
    group(&mut out, "Local_flag", LOCAL_FLAGS);
    group(&mut out, "Key_kind", KEY_KINDS);
    group(&mut out, "Kept_kind", KEPT_KINDS);
    group(&mut out, "Meta_owner", META_OWNERS);
    names(&mut out, "binops", &BINOPS);
    names(&mut out, "unops", &UNOPS);
    names(&mut out, "typed_expr_def", &TYPED_EXPR_DEF);
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}
